import './note-create.css';
import {
  NOTE_CLUSTERS,
  getQuickNoteBinding,
  getQuickNoteMagic,
  getSavedNoteCluster,
  isClusterAwareInterpreter,
  saveNoteCluster,
} from '../../app/quick-note.config';

angular.module('zeppelinWebApp').controller('NoteCreateCtrl', NoteCreateCtrl);

function NoteCreateCtrl($scope, noteListFactory, $routeParams, websocketMsgSrv) {
  'ngInject';

  let vm = this;
  vm.clone = false;
  vm.quickTag = null;
  vm.clusterOptions = NOTE_CLUSTERS;
  vm.selectedCluster = getSavedNoteCluster();
  vm.notes = noteListFactory;
  vm.websocketMsgSrv = websocketMsgSrv;
  $scope.note = {};
  $scope.interpreterSettings = {};
  $scope.note.defaultInterpreter = null;

  vm.createNote = function() {
    if (!vm.clone) {
      let defaultInterpreterGroup = '';
      if ($scope.note.defaultInterpreter !== null) {
        defaultInterpreterGroup = $scope.note.defaultInterpreter.name;
      }
      vm.websocketMsgSrv.createNotebook($scope.note.notename, defaultInterpreterGroup);
      $scope.note.defaultInterpreter = null;
    } else {
      let noteId = $routeParams.noteId;
      vm.websocketMsgSrv.cloneNote(noteId, $scope.note.notename);
    }
  };

  vm.handleNameEnter = function() {
    angular.element('#noteCreateModal').modal('toggle');
    vm.createNote();
  };

  vm.preVisible = function(clone, sourceNoteName, path) {
    vm.clone = clone;
    vm.quickTag = null;
    vm.selectedCluster = getSavedNoteCluster();
    vm.nameAutoGenerated = true;
    vm.sourceNoteName = sourceNoteName;
    if (vm.clone) {
      $scope.note.notename = vm.cloneNoteName();
    } else {
      vm.pendingPath = path;
      $scope.note.notename = '';
    }
    $scope.$apply();
  };

  vm.newNoteName = function(path) {
    let interpreterName = 'note';
    if ($scope.note.defaultInterpreter && $scope.note.defaultInterpreter.name) {
      interpreterName = $scope.note.defaultInterpreter.name;
    }
    let now = new Date();
    let pad = function(n) {
      return n < 10 ? '0' + n : '' + n;
    };
    let dateStr = '' + now.getFullYear() + pad(now.getMonth() + 1) + pad(now.getDate());
    let timeStr = '' + pad(now.getHours()) + pad(now.getMinutes()) + pad(now.getSeconds());
    return (path ? path + '/' : '') + interpreterName + '_' + dateStr + '_' + timeStr;
  };

  vm.cloneNoteName = function() {
    let copyCount = 1;
    let newCloneName = '';
    let lastIndex = vm.sourceNoteName.lastIndexOf(' ');
    let endsWithNumber = !!vm.sourceNoteName.match('^.+?\\s\\d$');
    let noteNamePrefix = endsWithNumber ? vm.sourceNoteName.substr(0, lastIndex) : vm.sourceNoteName;
    let regexp = new RegExp('^' + noteNamePrefix + ' .+');

    angular.forEach(vm.notes.flatList, function(noteName) {
      noteName = noteName.path;
      if (noteName.match(regexp)) {
        let lastCopyCount = noteName.substr(lastIndex).trim();
        newCloneName = noteNamePrefix;
        lastCopyCount = parseInt(lastCopyCount);
        if (copyCount <= lastCopyCount) {
          copyCount = lastCopyCount + 1;
        }
      }
    });

    if (!newCloneName) {
      newCloneName = vm.sourceNoteName;
    }
    return newCloneName + ' ' + copyCount;
  };

  vm.getInterpreterSettings = function() {
    vm.websocketMsgSrv.getInterpreterSettings();
  };

  vm.selectQuickTag = function(tag) {
    let targetName = getQuickNoteBinding(tag, vm.selectedCluster);
    let targetInterpreter = findInterpreterSetting(targetName);
    if (!targetInterpreter) {
      return;
    }
    vm.quickTag = tag;
    $scope.note.defaultInterpreter = targetInterpreter;
    if (!vm.clone && vm.nameAutoGenerated) {
      $scope.note.notename = vm.newNoteName(vm.pendingPath);
    }
  };

  vm.selectCluster = function(cluster) {
    vm.selectedCluster = cluster;
    saveNoteCluster(cluster);
    if (isClusterAwareInterpreter(vm.quickTag)) {
      vm.selectQuickTag(vm.quickTag);
    }
  };

  vm.getQuickTagMagic = function(tag) {
    return getQuickNoteMagic(tag, vm.selectedCluster);
  };

  vm.onInterpreterChange = function() {
    vm.quickTag = null;
    let interpreterName = $scope.note.defaultInterpreter && $scope.note.defaultInterpreter.name;
    if (interpreterName === 'hadoop3_hive' || interpreterName === 'hadoop3_spark') {
      vm.selectedCluster = 'hadoop3';
      saveNoteCluster(vm.selectedCluster);
    } else if (interpreterName === 'hive' || interpreterName === 'spark' || interpreterName === 'spark3') {
      vm.selectedCluster = 'hadoop2';
      saveNoteCluster(vm.selectedCluster);
    }
    if (!vm.clone && vm.nameAutoGenerated) {
      $scope.note.notename = vm.newNoteName(vm.pendingPath);
    }
  };

  $scope.onNoteNameChange = function() {
    vm.nameAutoGenerated = false;
  };

  $scope.$on('interpreterSettings', function(event, data) {
    $scope.interpreterSettings = data.interpreterSettings;
    // Don't auto-select an interpreter — let the user choose explicitly.
    $scope.note.defaultInterpreter = null;
    if (!vm.clone && vm.nameAutoGenerated) {
      $scope.note.notename = vm.newNoteName(vm.pendingPath);
    }
  });

  function findInterpreterSetting(name) {
    if (!angular.isArray($scope.interpreterSettings)) {
      return null;
    }
    for (let i = 0; i < $scope.interpreterSettings.length; i++) {
      if ($scope.interpreterSettings[i].name === name) {
        return $scope.interpreterSettings[i];
      }
    }
    return null;
  }
}
